const exercises = [];
let id = 1;

// Generate 350 exercises
for (let i = 0; i < 350; i++) {
  const contentIndex = i % hindiContent.length;
  let difficulty = "easy";
  let duration = 300;
  let titlePrefix = "आसान";
  
  if (i >= 120 && i < 240) {
    difficulty = "medium";
    duration = 360;
    titlePrefix = "मध्यम";
  } else if (i >= 240) {
    difficulty = "hard";
    duration = 420;
    titlePrefix = "कठिन";
  }
  
  const exerciseNum = i + 1;
  
  // Pure Hindi content - NO ENGLISH AT ALL
  const pureHindiContent = hindiContent[contentIndex] + 
    ` यह हिंदी टाइपिंग का ${titlePrefix} अभ्यास क्रमांक ${exerciseNum} है। नियमित रूप से अभ्यास करते रहें। आपकी हिंदी टाइपिंग में लगातार सुधार होता रहेगा। कुर्टी देव फ़ॉन्ट में हिंदी टाइपिंग सरल है। बस अभ्यास की आवश्यकता है। प्रतिदिन कम से कम पंद्रह मिनट टाइपिंग का अभ्यास करें। आपकी टाइपिंग गति तेजी से बढ़ेगी। सटीकता पर ध्यान दें। गति अपने आप बढ़ती जाएगी। हिंदी टाइपिंग में महारत हासिल करने के लिए अभ्यास जारी रखें। कुर्टी देव फ़ॉन्ट सरकारी कार्यालयों में प्रयोग होता है। इसलिए इसका अभ्यास करना अत्यंत महत्वपूर्ण है। आपकी मेहनत रंग लाएगी। सफलता निश्चित है। हिंदी टाइपिंग का यह अभ्यास आपको एक कुशल टाइपिस्ट बनाने में सहायक होगा। नियमित अभ्यास करते रहें। हिंदी टाइपिंग में आप निपुण हो जाएंगे। इस अभ्यास को बार-बार दोहराएं। इससे आपकी टाइपिंग गति में वृद्धि होगी। कुर्टी देव फ़ॉन्ट सबसे लोकप्रिय हिंदी फ़ॉन्ट है। इसके अभ्यास से आप आसानी से हिंदी टाइप कर सकेंगे। यह फ़ॉन्ट विशेष रूप से सरकारी कामों के लिए उपयुक्त है। इसका अभ्यास जारी रखें।`;
  
  exercises.push({
    id: id++,
    title: `हिंदी टाइपिंग अभ्यास - ${titlePrefix} ${exerciseNum}`,
    description: `कुर्टी देव फ़ॉन्ट में हिंदी टाइपिंग का ${titlePrefix} अभ्यास भाग ${exerciseNum}`,
    difficulty: difficulty,
    duration: duration,
    content: pureHindiContent
  });
}

const output = {
  language: "hindi",
  font: "kurti-dev",
  totalExercises: exercises.length,
  exercises: exercises
};

const outputPath = path.join(__dirname, '../src/data/hindi-kurtidev-exercises.json');
fs.writeFileSync(outputPath, JSON.stringify(output, null, 2));

