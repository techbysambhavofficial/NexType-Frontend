const exercises = [];
let id = 1;

// 120 आसान अभ्यास
for (let i = 0; i < 120; i++) {
  const index = i % easyContent.length;
  const num = i + 1;
  exercises.push({
    id: id++,
    title: `हिंदी टाइपिंग अभ्यास ${Math.floor(i / 20) + 1} - आसान ${num}`,
    description: `मंगल फ़ॉन्ट में हिंदी टाइपिंग का आसान अभ्यास - भाग ${num}`,
    difficulty: "easy",
    duration: 300,
    content: easyContent[index]
  });
}

// 120 मध्यम अभ्यास
